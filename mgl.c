static void mgl_internal_log(int id, const char *fmt, ...)
{
	va_list l;

	if (!mgl.user_debug) return;
	else va_start(l, fmt);

	{
		char buffer[4096];
		vsnprintf(buffer, sizeof buffer, fmt, l);
		mgl.user_debug(id, buffer);
	}

	va_end(l);
}

